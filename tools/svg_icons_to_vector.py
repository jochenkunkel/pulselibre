#!/usr/bin/env python3
"""Converts design/icons/v1/*.svg (PulsLibre icon system) into Android VectorDrawables and rebuilds the contact sheet.

Usage: python3 -I tools/svg_icons_to_vector.py
Only the constructs used by the icon set are supported (path, rect with rx, circle, ellipse, classes line/f/dot).
Colours come from @color/pl_icon_* so light/dark themes can tint them (values / values-night).
"""
import glob, os, re, sys

SRC = os.path.join(os.path.dirname(__file__), '..', 'design', 'icons', 'v1')
DST = os.path.join(os.path.dirname(__file__), '..', 'app', 'src', 'main', 'res', 'drawable')

def fmt(v):
    v = float(v)
    return str(int(v)) if v == int(v) else ('%.3f' % v).rstrip('0').rstrip('.')

def rect_path(x, y, w, h, rx):
    x, y, w, h, rx = map(float, (x, y, w, h, rx))
    r = min(rx, w / 2, h / 2)
    return (f"M{fmt(x + r)},{fmt(y)}H{fmt(x + w - r)}A{fmt(r)},{fmt(r)} 0 0 1 {fmt(x + w)},{fmt(y + r)}"
            f"V{fmt(y + h - r)}A{fmt(r)},{fmt(r)} 0 0 1 {fmt(x + w - r)},{fmt(y + h)}"
            f"H{fmt(x + r)}A{fmt(r)},{fmt(r)} 0 0 1 {fmt(x)},{fmt(y + h - r)}"
            f"V{fmt(y + r)}A{fmt(r)},{fmt(r)} 0 0 1 {fmt(x + r)},{fmt(y)}Z")

def ellipse_path(cx, cy, rx, ry):
    cx, cy, rx, ry = map(float, (cx, cy, rx, ry))
    return (f"M{fmt(cx - rx)},{fmt(cy)}A{fmt(rx)},{fmt(ry)} 0 1 0 {fmt(cx + rx)},{fmt(cy)}"
            f"A{fmt(rx)},{fmt(ry)} 0 1 0 {fmt(cx - rx)},{fmt(cy)}Z")

def attrs(tag):
    return dict(re.findall(r'([\w-]+)="([^"]*)"', tag))

def shapes(svg):
    body = re.search(r'<g class="line">(.*)</g>', svg, re.S).group(1)
    for m in re.finditer(r'<(path|rect|circle|ellipse)\b([^>]*)/?>', body):
        kind, a = m.group(1), attrs(m.group(2))
        cls = a.get('class', 'line')
        if kind == 'path': d = a['d']
        elif kind == 'rect': d = rect_path(a['x'], a['y'], a['width'], a['height'], a.get('rx', 0))
        elif kind == 'circle': d = ellipse_path(a['cx'], a['cy'], a['r'], a['r'])
        else: d = ellipse_path(a['cx'], a['cy'], a['rx'], a['ry'])
        yield cls, d

def vector(name, svg):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           f'<!-- Generated by tools/svg_icons_to_vector.py from design/icons/v1/{name}.svg – do not edit by hand. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="24dp" android:height="24dp" android:viewportWidth="128" android:viewportHeight="128">']
    for cls, d in shapes(svg):
        if cls == 'f':
            out.append(f'    <path android:pathData="{d}" android:fillColor="@color/pl_icon_fill" />')
        elif cls == 'dot':
            out.append(f'    <path android:pathData="{d}" android:fillColor="@color/pl_icon_accent" />')
        else:
            out.append(f'    <path android:pathData="{d}" android:strokeColor="@color/pl_icon_line" android:strokeWidth="6" '
                       'android:strokeLineCap="round" android:strokeLineJoin="round" />')
    out.append('</vector>')
    return '\n'.join(out) + '\n'

def contact_sheet(names):
    cols, cell = 8, 150
    rows = (len(names) + cols - 1) // cols
    w, h = cols * cell + 20, rows * (cell + 28) + 50
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" role="img" aria-label="PulsLibre Icon System v1 – alle {len(names)} Symbole">',
             f'<rect width="{w}" height="{h}" fill="#0d1124"/>',
             f'<text x="20" y="30" fill="#e9e1f7" font-family="Arial,Helvetica,sans-serif" font-size="18" font-weight="700">PulsLibre Icon System v1 · {len(names)} Symbole</text>']
    for i, n in enumerate(names):
        x, y = 10 + (i % cols) * cell, 50 + (i // cols) * (cell + 28)
        svg = open(os.path.join(SRC, n + '.svg')).read()
        inner = re.search(r'<g class="line">.*</g>', svg, re.S).group(0)
        # inline presentation attributes instead of CSS classes: renders in every SVG viewer
        inner = inner.replace('<g class="line">', '<g fill="none" stroke="#b68aff" stroke-width="6" stroke-linecap="round" stroke-linejoin="round">')
        inner = inner.replace('class="f"', 'fill="#6334a8" fill-opacity=".18" stroke="none"').replace('class="dot"', 'fill="#24e2bf" stroke="none"')
        parts.append(f'<g transform="translate({x + 11},{y})">{inner}</g>')
        parts.append(f'<text x="{x + 75}" y="{y + 146}" text-anchor="middle" fill="#d6cbe7" font-family="Arial,Helvetica,sans-serif" font-size="12">{n}</text>')
    parts.append('</svg>')
    return '\n'.join(parts)

def main():
    names = sorted(os.path.basename(f)[:-4] for f in glob.glob(os.path.join(SRC, '*.svg')) if 'contact-sheet' not in f)
    os.makedirs(DST, exist_ok=True)
    for n in names:
        svg = open(os.path.join(SRC, n + '.svg')).read()
        open(os.path.join(DST, 'ic_pl_' + n.replace('-', '_') + '.xml'), 'w').write(vector(n, svg))
    open(os.path.join(SRC, 'icon-contact-sheet.svg'), 'w').write(contact_sheet(names))
    print(len(names), 'icons converted')

if __name__ == '__main__':
    sys.exit(main())
